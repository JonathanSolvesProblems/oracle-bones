// The prismatic and irregular search results, recorded before the circle-outputs change to
// search.ts (.kiro/specs/circle-outputs, task 2; requirement 3.6).
//
// For every trapezoid, V-ditch, rectangle and irregular golden whose form is read without a
// hold, so that it reaches the search, this runs the search exactly as its mode calls it and
// records the returned depth, value and trial count. Doubles are written as exact decimal
// strings, so the comparison in search.test.ts is exact.
//
// The fixture is written only by the explicit command, never by a test run:
//   npm run snapshot:search        (in app/; node test/searchSnapshot.ts write)
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { PRISMATIC_STEP } from '../src/solver/constants.ts';
import { readRegularForm } from '../src/solver/forms.ts';
import { criticalDischarge } from '../src/solver/modes/criticalDepth.ts';
import { normalDischarge, prismOf } from '../src/solver/modes/normalDepth.ts';
import { irregularNormalWs, readIrregular } from '../src/solver/modes/normalDepthIrregular.ts';
import { search, type SearchResult } from '../src/solver/search.ts';
import type { RegularMode, RegularShape } from '../src/solver/types.ts';
import { ROOT, goldens } from './golden.ts';

export const SNAPSHOT_PATH = join(ROOT, 'app', 'test', 'fixtures', 'search-snapshot.json');

const PRISMATIC = new Set(['trapezoid', 'v_ditch', 'rectangle']);
const SEARCHING_MODES = new Set(['normal_depth', 'critical_depth']);

export type SnapshotEntry =
  | { pair: string; ok: true; depth: string; value: string; trials: number }
  | { pair: string; ok: false; reason: string };

/** The exact decimal value of a double (every binary fraction has a finite decimal form). */
export function exactDecimal(x: number): string {
  if (!Number.isFinite(x)) return String(x);
  if (x === 0) return Object.is(x, -0) ? '-0' : '0';
  const view = new DataView(new ArrayBuffer(8));
  view.setFloat64(0, x);
  const bits = view.getBigUint64(0);
  const sign = bits >> 63n ? '-' : '';
  const expBits = Number((bits >> 52n) & 0x7ffn);
  const frac = bits & ((1n << 52n) - 1n);
  const mant = expBits === 0 ? frac : frac | (1n << 52n);
  const exp = (expBits === 0 ? 1 : expBits) - 1075; // value = mant · 2^exp
  if (exp >= 0) return sign + (mant << BigInt(exp)).toString();
  // mant / 2^k = mant · 5^k / 10^k
  const k = -exp;
  const digits = (mant * 5n ** BigInt(k)).toString().padStart(k + 1, '0');
  let int = digits.slice(0, digits.length - k);
  let dec = digits.slice(digits.length - k).replace(/0+$/, '');
  if (int === '') int = '0';
  return sign + int + (dec ? `.${dec}` : '');
}

/** The search a prismatic or irregular golden reaches, run as its mode runs it; null if held. */
export function searchOf(g: { mode: string; shape: string; inputs: Record<string, string> }): SearchResult | null {
  if (!SEARCHING_MODES.has(g.mode)) return null;
  if (PRISMATIC.has(g.shape)) {
    const form = readRegularForm(g.mode as RegularMode, g.shape as RegularShape, g.inputs);
    if (!form.ok) return null;
    const v = form.values;
    const prism = prismOf(v);
    const F = g.mode === 'normal_depth' ? normalDischarge(prism, v.n!, v.slope!) : criticalDischarge(prism);
    return search(F, v.discharge!, { bottom: 0, first: PRISMATIC_STEP, step: PRISMATIC_STEP });
  }
  if (g.shape === 'irregular' && g.mode === 'normal_depth') {
    const read = readIrregular(g.inputs);
    if (!read.ok) return null;
    const { section, discharge, slope, lowest } = read.value;
    return irregularNormalWs(section, discharge, slope, lowest);
  }
  return null;
}

export function entryOf(pair: string, r: SearchResult): SnapshotEntry {
  return r.ok
    ? { pair, ok: true, depth: exactDecimal(r.y), value: exactDecimal(r.value), trials: r.trials }
    : { pair, ok: false, reason: r.reason };
}

/** Every prismatic and irregular golden that reaches the search, keyed by case id. */
export function computeSnapshot(): Record<string, SnapshotEntry> {
  const out: Record<string, SnapshotEntry> = {};
  for (const g of goldens()) {
    if (g.id.startsWith('obs-') || g.outcome === 'observed') continue;
    const r = searchOf(g);
    if (r) out[g.id] = entryOf(`${g.mode}/${g.shape}`, r);
  }
  return out;
}

if (process.argv[2] === 'write') {
  const commit = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: ROOT, encoding: 'utf-8' }).trim();
  const dirty = execFileSync('git', ['status', '--porcelain', '--', 'app/src'], { cwd: ROOT, encoding: 'utf-8' }).trim();
  if (dirty) throw new Error(`app/src has uncommitted changes; the snapshot must come from a commit:\n${dirty}`);
  const entries = computeSnapshot();
  const note = `Generated by "npm run snapshot:search" (app/test/searchSnapshot.ts) at commit ${commit}, `
    + 'from search.ts before the circle-outputs change. Do not edit by hand; search.test.ts compares against it.';
  writeFileSync(SNAPSHOT_PATH, `${JSON.stringify({ _note: note, ...entries }, null, 2)}\n`, 'utf-8');
  const pairs = new Map<string, number>();
  for (const e of Object.values(entries)) pairs.set(e.pair, (pairs.get(e.pair) ?? 0) + 1);
  console.log(`${Object.keys(entries).length} searches written to ${SNAPSHOT_PATH}`);
  for (const [p, n] of [...pairs].sort()) console.log(`  ${p}: ${n}`);
}
